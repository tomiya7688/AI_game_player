"""Print facts from a Markdown design document that help draw a diagram by hand.

Diagrams that can be derived from code are generated by tools/generate_docs.py.
This script covers the rest (flows, responsibility boundaries): it extracts the
headings, table rows, linked documents and Issue numbers so that the diagram
draft starts from facts instead of a full re-read.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

LINK_PATTERN = re.compile(r"\[[^\]]*\]\((?P<target>[^)#]+\.md)[^)]*\)")
ISSUE_PATTERN = re.compile(r"#(?P<number>\d{2,5})\b")
IDENTIFIER_PATTERN = re.compile(r"`(?P<name>[A-Za-z_][A-Za-z0-9_.]{2,})`")


def extract_hints(text: str) -> str:
    """Return a Markdown summary of structure facts for diagram drafting."""
    headings: list[str] = []
    table_rows: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if line.startswith("#"):
            headings.append(line.rstrip())
        elif line.startswith("|") and not re.match(r"^\|[-| :]+\|$", line):
            table_rows.append(line.rstrip())
    links = sorted({m.group("target") for m in LINK_PATTERN.finditer(text)})
    issues = sorted({int(m.group("number")) for m in ISSUE_PATTERN.finditer(text)})
    names = sorted({m.group("name") for m in IDENTIFIER_PATTERN.finditer(text)})
    # (題名, 項目, 素のまま出すか)。見出しと表の行は元の書式のまま、他は箇条書きにする。
    sections = [
        ("見出し（図の節の候補）", headings, True),
        ("表の行（箱と関係の候補）", table_rows, True),
        ("参照している文書（図の外側の箱）", links, False),
        ("参照しているIssue", [f"#{n}" for n in issues], False),
        ("コード上の名前（箱の名前）", names, False),
    ]
    output: list[str] = []
    for title, items, raw in sections:
        output += [f"## {title}", ""]
        output += (items if raw else [f"- {item}" for item in items]) or ["- (なし)"]
        output.append("")
    return "\n".join(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("document", type=Path, help="Markdown design document")
    args = parser.parse_args()
    print(extract_hints(args.document.read_text(encoding="utf-8")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
